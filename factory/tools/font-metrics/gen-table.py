#!/usr/bin/env python3
"""Turns font-metrics' JSON output into packages/SwiftRightHost/Sources/SwiftRightHost/FontMetricTableData.swift (data only: measured numbers, face names, no font software).
usage: gen-table.py <font-metrics-output.json> <YYYY-MM-DD> [out.swift]
The header names the macOS build, the tool version and the date; the date is an argument so that the tool output itself stays clock-free."""
import json, sys
from pathlib import Path

src, date = sys.argv[1], sys.argv[2]
out = Path(sys.argv[3]) if len(sys.argv) > 3 else Path(__file__).resolve().parents[3] / "packages/SwiftRightHost/Sources/SwiftRightHost/FontMetricTableData.swift"
d = json.loads(Path(src).read_text())

def compact(v): return json.dumps(v, sort_keys=True, separators=(",", ":"), ensure_ascii=False)

lines = ["{"]
keys = sorted(d)
for ki, k in enumerate(keys):
    v = d[k]; comma = "," if ki < len(keys) - 1 else ""
    if isinstance(v, dict) and k not in ("columns",) and len(compact(v)) > 400:
        lines.append(f' "{k}": {{')
        items = sorted(v.items())
        for i, (kk, vv) in enumerate(items):
            lines.append(f'  {json.dumps(kk, ensure_ascii=False)}: {compact(vv)}{"," if i < len(items) - 1 else ""}')
        lines.append(f" }}{comma}")
    else:
        lines.append(f' "{k}": {compact(v)}{comma}')
lines.append("}")
body = "\n".join(lines)
assert '"""#' not in body
json.loads(body)
header = (f"// Generated by factory/tools/font-metrics/gen-table.py from factory/tools/font-metrics/font-metrics.sh ({d['tool']}); do not edit.\n"
          f"// Measured on macOS {d['macOS']} (kern.osversion {d['macOSBuild']}), {date}, in an offscreen NSHostingView at screen scale 1 and 2.5 (decision C12).\n"
          "// Data only: measured line metrics, baselines, widths and face names. No font software, no outlines. Not yet used by the runtime text path (block F2).\n")
out.write_text(header + "enum FontMetricTableData {\n    static let json = #\"\"\"\n" + body + "\n\"\"\"#\n}\n", encoding="utf-8")
print("wrote", out, len(body), "bytes of JSON")
