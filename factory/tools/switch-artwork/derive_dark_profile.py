#!/usr/bin/env python3
"""Derives packages/SwiftRightHost/Sources/SwiftRightHost/ToggleDarkData.swift: the DARK-appearance numbers of the switch and the checkbox, measured from Mac captures
(offscreen NSHostingView, window appearance darkAqua, colour scheme dark, scale 2.5; docs/sr1-decisions.md items 7 and 11). Geometry (end caps, check strokes, the disabled
edge-coverage curve) is shared with the light profile; only flat colours, the knob's translucency and the knob shadow change.
usage: derive_dark_profile.py <blocks-17-20/swiftui.color-scheme dir> <output ToggleDarkData.swift>
Needs <dir>/{switch,checkbox}-{on,off}-dark[-disabled]-v1/runs/mac-measure/mac/run-01.png (pair.py <case> --runs 1 --skip-windows --out <case>/runs/mac-measure)."""
import sys
from pathlib import Path
from PIL import Image

root = Path(sys.argv[1])
def load(n): return Image.open(root / n / "runs/mac-measure/mac/run-01.png").convert("RGB").load()
sw = {k: load(f"switch-{k}-v1") for k in ("on-dark", "off-dark", "on-dark-disabled", "off-dark-disabled")}
cb = {k: load(f"checkbox-{k}-v1") for k in ("on-dark", "off-dark", "on-dark-disabled", "off-dark-disabled")}
rgb = lambda c: "0x%02x%02x%02x" % c[:3]

# switch: flat track away from the knob (centre row, 4 px from the near end), knob = white at alpha a over the track: a = (knob - track) / (255 - track)
track = {"on": sw["on-dark"][8, 30], "off": sw["off-dark"][110, 30], "onDisabled": sw["on-dark-disabled"][8, 30], "offDisabled": sw["off-dark-disabled"][110, 30]}
knob = {"on": sw["on-dark"][90, 30], "off": sw["off-dark"][30, 30], "onDisabled": sw["on-dark-disabled"][90, 30], "offDisabled": sw["off-dark-disabled"][30, 30]}
alphas = [(knob[k][c] - track[k][c]) / (255 - track[k][c]) for k in track for c in range(3) if 255 - track[k][c] > 100]
knob_alpha = sum(alphas) / len(alphas)
# knob shadow: darkest track pixel next to the knob vs the flat track (dark appearance casts none worth modelling: report it)
shadow = max(0, (track["off"][0] - min(sw["off-dark"][x, 30][0] for x in range(86, 100))) / track["off"][0])

# checkbox: flat box colour (a pixel left of the check), check colour = brightest pixel of the on states
box = {"on": cb["on-dark"][6, 30], "off": cb["off-dark"][30, 30], "onDisabled": cb["on-dark-disabled"][6, 30], "offDisabled": cb["off-dark-disabled"][30, 30]}
def brightest(im): return max(((im[x, y]) for x in range(40) for y in range(40)), key=lambda c: sum(c))
check, check_dis = brightest(cb["on-dark"]), brightest(cb["on-dark-disabled"])

out = f"""// GENERATED by factory/tools/switch-artwork/derive_dark_profile.py from Mac captures of SwiftUI's switch and default Toggle (a checkbox) at scale 2.5, DARK appearance.
// Numbers only: flat state colours, the knob's translucency (white at `knobAlpha` over the track) and the knob shadow. No Apple artwork is embedded.
// Geometry (end caps, check strokes, the disabled edge-coverage curve) is the light profile's.
enum ToggleDarkData {{
    static let trackOn: UInt32 = {rgb(track['on'])}
    static let trackOff: UInt32 = {rgb(track['off'])}
    static let trackOnDisabled: UInt32 = {rgb(track['onDisabled'])}
    static let trackOffDisabled: UInt32 = {rgb(track['offDisabled'])}
    /// The knob is white at this opacity over the track (it is opaque white in the light appearance).
    static let knobAlpha: Double = {knob_alpha:.4f}
    /// Measured darkening next to the knob, as a fraction of the track colour ({shadow:.4f}: none is modelled in dark).
    static let shadowStrength: Double = 0.0

    static let boxOn: UInt32 = {rgb(box['on'])}
    static let boxOff: UInt32 = {rgb(box['off'])}
    static let boxOnDisabled: UInt32 = {rgb(box['onDisabled'])}
    static let boxOffDisabled: UInt32 = {rgb(box['offDisabled'])}
    static let checkOn: UInt32 = {rgb(check)}
    static let checkOnDisabled: UInt32 = {rgb(check_dis)}
}}
"""
Path(sys.argv[2]).write_text(out)
print(out)
