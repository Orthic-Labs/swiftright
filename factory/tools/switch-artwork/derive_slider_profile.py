#!/usr/bin/env python3
"""Derives SliderArtworkData.swift (packages/SwiftRightHost) from Mac captures of SwiftUI's Slider at scale 2.5 (inputs in slider-inputs/: the probes of
factory/pipeline/blocks-37-38, light appearance over black and white, dark appearance over black and white, disabled light over white).
Numbers only (decision H4): no Apple artwork is embedded; the thumb body mask and its shadow are fitted planes, the track end caps coverage tables.

Model (all in device pixels at scale 2.5; per pixel, over any background):
  thumb mask m(x, y), shadow s(x, y), body alpha a (1.0 light, 217/255 dark), a track layer (Pt premultiplied colour, at alpha) made of the empty track
  (black / white at alpha 25/255) and the fill (accent, opaque; disabled: black / white at alpha 37/255 and 36/255 REPLACING the track under it);
    alpha  = 1 - (1 - a m)(1 - s)(1 - at (1 - h))          h = m for a translucent (dark) body, 0 for an opaque one
    colour = 255 a m + (1 - a m)(1 - s)(1 - h) Pt
  Validated against every probe capture: <= 4 levels at the track end caps, <= 1 elsewhere (docs/sr1-decisions.md H4).
usage: derive_slider_profile.py   (writes ../../packages/SwiftRightHost/Sources/SwiftRightHost/SliderArtworkData.swift)"""
import base64, struct
from pathlib import Path
from PIL import Image
H = Path(__file__).resolve().parent
OUT = H.parents[2] / "packages/SwiftRightHost/Sources/SwiftRightHost/SliderArtworkData.swift"
IN = H / "slider-inputs"
M, W, HH = 16, 50, 40
A = 25 / 255.0


def derive(png, black_top, white_top, light, left=375):
    im = Image.open(png).convert("RGB")
    P = lambda x, y: im.getpixel((x, y))[0]
    a = max(P(left + 25, black_top + j) for j in range(HH)) / 255.0
    m = [[0.0] * W for _ in range(HH)]
    s = [[0.0] * (W + 2 * M) for _ in range(HH + 2 * M)]
    for j in range(-M, HH + M):
        for i in range(-M, W + M):
            ii = i if i >= W // 2 else W - 1 - i                      # the thumb is symmetric: the right half, mirrored
            band = 13 <= j < 27
            p0, pw = P(left + ii, black_top + j), P(left + ii, white_top + j)
            Pt = 0.0 if light else 255 * A
            def Qof(mm):
                Uw = (255 * (1 - A) if band else 255.0) if light else 255.0
                return (pw - 255 * a * mm) / Uw
            def resid(mm):
                Ub = Pt * (1 - mm) if band else 0.0
                return 255 * a * mm + Qof(mm) * Ub - p0
            lo, hi = 0.0, 1.0
            if resid(lo) > 0: mm = 0.0
            elif resid(hi) < 0: mm = 1.0
            else:
                for _ in range(50):
                    mid = (lo + hi) / 2
                    if resid(mid) < 0: lo = mid
                    else: hi = mid
                mm = (lo + hi) / 2
            den = 1 - a * mm
            sv = 1 - Qof(mm) / den if den > 1e-6 else 0.0
            if mm >= 0.999: sv = 0.0
            if 0 <= i < W and 0 <= j < HH: m[j][i] = mm
            s[j + M][i + M] = min(1.0, max(0.0, sv))
    return a, m, s


def caps(png, top=180):
    im = Image.open(png).convert("RGB")
    capE = [[0.0] * 8 for _ in range(14)]; capF = [[0.0] * 8 for _ in range(14)]
    for j in range(14):
        for i in range(8):
            capE[j][i] = min(1.0, max(0.0, (255 - im.getpixel((649 - i, top + 13 + j))[0]) / 25.0))
            under = 255 * (1 - A * capE[j][i])
            capF[j][i] = min(1.0, max(0.0, 1 - im.getpixel((150 + i, top + 13 + j))[0] / under))
    return capE, capF


def b64u16(rows, scale=4095):
    return base64.b64encode(b"".join(struct.pack("<H", round(v * scale)) for r in rows for v in r)).decode()


def b64u8(rows):
    return base64.b64encode(bytes(round(v * 255) for r in rows for v in r)).decode()


a_l, m_l, s_l = derive(IN / "light-black-white-v50.png", 80, 180, True)
a_d, m_d, s_d = derive(IN / "dark-black-white-v50.png", 40, 160, False)
capE, capF = caps(IN / "light-black-white-v50.png")
src = f"""// GENERATED by factory/tools/switch-artwork/derive_slider_profile.py from Mac captures of SwiftUI's Slider at scale 2.5 (decision H4 of docs/sr1-decisions.md).
// Numbers only: the thumb's body mask and shadow (50 x 40 and 82 x 72 planes, 16-bit, x4095), the track's end-cap coverage (14 x 8, 8-bit) and the measured colours. No Apple artwork is embedded.
enum SliderArtworkData {{
    static let thumbWidthPX = {W}, thumbHeightPX = {HH}, shadowMarginPX = {M}, trackHeightPX = 14
    static let trackAlpha = 25.0 / 255.0
    // light
    static let lightBodyAlpha = {a_l!r}
    static let lightMask = "{b64u16(m_l)}"
    static let lightShadow = "{b64u16(s_l)}"
    // dark
    static let darkBodyAlpha = {a_d!r}
    static let darkMask = "{b64u16(m_d)}"
    static let darkShadow = "{b64u16(s_d)}"
    // end caps: the empty track's, and the fill's over it (left end; mirrored for the right end)
    static let capEmpty = "{b64u8(capE)}"
    static let capFill = "{b64u8(capF)}"
    // colours (R, G, B): the accent fill, and the disabled fill's alpha (over black for light, over white for dark)
    static let lightAccent: (Double, Double, Double) = (0, 120, 249)
    static let darkAccent: (Double, Double, Double) = (6, 126, 255)
    static let lightDisabledFillAlpha = 37.0 / 255.0
    static let darkDisabledFillAlpha = 36.0 / 255.0
}}
"""
OUT.write_text(src)
# golden samples (Mac captures over white, v50, width 500): rows and columns of the control for the unit test
def golden(png, white_top, name):
    im = Image.open(png).convert("RGB")
    rows = {}
    for y in (-8, 3, 13, 14, 20, 26, 27, 36, 46):
        rows[y] = [im.getpixel((150 + x, white_top + y))[0] for x in range(-16, 516)]
    cols = {x: [im.getpixel((150 + x, white_top + y))[0] for y in range(-16, 56)] for x in (0, 3, 100, 224, 225, 226, 250, 274, 275, 300, 499)}
    return rows, cols
GOLD = H.parents[2] / "packages/SwiftRightHost/Tests/SwiftRightHostTests/SliderArtworkGolden.swift"
lr, lc = golden(IN / "light-black-white-v50.png", 180, "light")
dr, dc = golden(IN / "dark-black-white-v50.png", 160, "dark")
def swift_rows(d): return "[" + ", ".join(f"{k}: {v}" for k, v in d.items()) + "]"
GOLD.write_text("// GENERATED by factory/tools/switch-artwork/derive_slider_profile.py: red channel of Mac captures of a 500 x 40 px Slider at value 50 (thumb offset 225), over white;\n// rows y (-16 ..< 516 for x) and columns x (-16 ..< 56 for y) around the control, light and dark.\nenum SliderArtworkGolden {\n"
  f"    static let lightRows: [Int: [Int]] = {swift_rows(lr)}\n    static let lightCols: [Int: [Int]] = {swift_rows(lc)}\n"
  f"    static let darkRows: [Int: [Int]] = {swift_rows(dr)}\n    static let darkCols: [Int: [Int]] = {swift_rows(dc)}\n}}\n")
print("wrote", GOLD)
print("wrote", OUT, len(src), "bytes; light a", a_l, "dark a", a_d)
