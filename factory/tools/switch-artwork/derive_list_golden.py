#!/usr/bin/env python3
"""Derives packages/SwiftRightHost/Tests/SwiftRightHostTests/ListPaintGolden.swift from Mac captures of SwiftUI's default List (list-profile/list_probe.swift, scale 2.5,
light appearance, an NSTableView-backed List in an NSHostingView in a window that is never shown; the list is 200 x 150 pt at (150, 112.5) px).
Numbers only: a separator cross-section (and the top-left corner of the selection highlight, 36 x 36 px, kept as evidence; its radius is circular 8 pt = 20 px at scale 2.5: the best fit of a circle against these pixels over the rows free of text is 20 px, worst channel difference 74 on one pixel, from the half-pixel list position of the capture). usage: derive_list_golden.py <captures dir> <out.swift>"""
import sys
from pathlib import Path
from PIL import Image
root = Path(sys.argv[1])
im = Image.open(root / "five-sel2.png").convert("RGB").load()
# selected row 2 spans y 258..317 and its highlight x 175..624
corner = ["".join("%02x%02x%02x" % im[175 + x, 258 + y] for x in range(36)) for y in range(36)]
sep = ["%02x%02x%02x" % im[300, y] for y in range(193, 200)]       # separator under row 0: rows 195..197
Path(sys.argv[2]).write_text("// GENERATED by factory/tools/switch-artwork/derive_list_golden.py from Mac captures of SwiftUI's default List at scale 2.5 (light).\n"
    "enum ListPaintGolden {\n    /// 36 x 36 px at the top-left of a selected row's highlight (accent fill over white), row-major hex RGB.\n    static let selectionCorner: [String] = [\n"
    + "".join(f'        "{r}",\n' for r in corner) + "    ]\n    /// The pixels at y 193...199 down a column of the separator under the first row (the list's first row is y 138..197).\n    static let separatorColumn: [String] = [" + ", ".join(f'"{s}"' for s in sep) + "]\n}\n")
print(sep)


# ---- the selection highlight's corner outline (points), derived like the Button's (derive_button_profile.py): from the accent capture (white to (0,100,225): 255 levels
# of contrast), over the 20 columns x 16 rows free of the row's text. usage with a third argument: <out ListHighlightData.swift>
if len(sys.argv) > 3:
    S = 2.5
    fill = im[300, 280]
    cov = lambda x, y: max(0.0, min(1.0, (255 - im[175 + x, 258 + y][0]) / (255 - fill[0])))
    pts = []
    for y in range(26):                                   # left boundary of row y over the 15 columns left of the row's text
        x = sum(1 - cov(x, y) for x in range(15))
        if x < 14.5: pts.append((x, y + 0.5))
    for x in range(36):                                   # top boundary of column x over the 16 rows above the row's text
        y = sum(1 - cov(x, y) for y in range(16))
        if y < 15.5: pts.append((x + 0.5, y))
    pts.append((36.0, 0.0))
    pts.sort(); chain = []
    for x, y in pts:
        x, y = round(x / S, 4), round(y / S, 4)
        if chain and x <= chain[-1][0] + 1e-9: continue
        if chain and y > chain[-1][1] + 1e-9: continue
        chain.append((x, y))
    if chain[0][0] > 0.0: chain.insert(0, (0.0, chain[0][1]))
    body = ",\n        ".join(", ".join(f"({x}, {y})" for x, y in chain[i:i + 4]) for i in range(0, len(chain), 4))
    Path(sys.argv[3]).write_text(f"""// GENERATED by factory/tools/switch-artwork/derive_list_golden.py from a Mac capture of SwiftUI's default List with a selected row at scale 2.5, light.
// Numbers only: the corner outline of the selection highlight. No Apple artwork is embedded.
enum ListHighlightData {{
    /// Top-left corner in points: (x from the left edge, y of the highlight's top edge above that column); y reaches 0 at the straight top.
    static let corner: [(x: Double, y: Double)] = [
        {body},
    ]
}}
""")
