#!/usr/bin/env python3
"""Derives the data of packages/SwiftRightHost/Sources/SwiftRightHost/SwitchArtworkData.swift from Mac captures of the four switch states.
The artwork is our own vector model of SwiftUI's macOS switch (not Apple assets): this script only measures *numbers* from the reference
renders (outline of the two end caps, flat state colours, the disabled edge-coverage curve); it never copies pixels.

usage: derive_switch_profile.py <dir with switch-on-v1, switch-off-v1, toggle-on-disabled-v1, toggle-off-disabled-v1 each holding mac/run-01.png> <output SwitchArtworkData.swift>
Captures: python3 factory/tools/pair.py <case> --runs 1 --skip-windows --out <dir>/<case-name>   (Mac host: factory/pipeline/blocks-6-10/shared-mac-host)
The captures are 800x600 at scale 2.5 with the switch at the top-left (frame 54x24 pt = 135x60 px)."""
import sys, statistics
from pathlib import Path
from PIL import Image

S = 2.5
root = Path(sys.argv[1])
def load(n): return Image.open(root / n / "mac/run-01.png").convert("RGB").load()
on, off, don, doff = (load(n) for n in ("switch-on-v1", "switch-off-v1", "toggle-on-disabled-v1", "toggle-off-disabled-v1"))

# --- cap outlines from the enabled ON capture, R channel: track R=0 on white 255, knob R=255 on track R=0 (both exact, unaffected by the shadow)
track_cov = lambda x, y: (255 - on[x, y][0]) / 255
knob_cov = lambda x, y: on[x, y][0] / 255
def chain(rows, cols, rowedge, coledge, x0, y0, end):
    pts = [(rowedge(y) - x0, y + 0.5 - y0) for y in rows] + [(x + 0.5 - x0, coledge(x) - y0) for x in cols] + [(end, 0.0)]
    pts.sort(); out = []
    for x, y in pts:
        if out and x <= out[-1][0] + 1e-9: continue
        if out and y > out[-1][1] + 1e-9: continue
        out.append((x, y))
    return out
track = chain(list(range(29, 1, -1)), range(10, 42),
              lambda y: 48 - sum(track_cov(x, y) for x in range(0, 48)),      # left boundary of row y (area under the cap)
              lambda x: 30 - sum(track_cov(x, y) for y in range(0, 30)), 0, 0, 42.5)  # top boundary of column x
knob = chain(list(range(29, 8, -1)), range(60, 90),
             lambda y: 100 - sum(knob_cov(x, y) for x in range(50, 100)),
             lambda x: 30 - sum(knob_cov(x, y) for y in range(5, 30)), 50, 5, 40.5)
pt = lambda ch: [(round(x / S, 4), round(y / S, 4)) for x, y in ch]

# --- flat state colours (the track colour away from the knob, centre row, 4 px in from the left end)
flat_on = lambda im: im[8, 30]      # ON: knob is at the right, the left end is flat track
flat_off = lambda im: im[110, 30]   # OFF: knob is at the left, the right end is flat track
# --- disabled edge-coverage curve: enabled-ON vs disabled-ON coverage of the same track edge pixels
bins = {}
rdis = flat_on(don)[0]
for y in range(60):
    for x in range(45):
        ce = (255 - on[x, y][0]) / 255; cd = (255 - don[x, y][0]) / (255 - rdis)
        if 0.02 < ce < 0.98: bins.setdefault(min(9, int(ce * 10)), []).append((ce, cd))
lut = [(0.0, 0.0)] + [(round(statistics.mean(p[0] for p in v), 3), round(statistics.mean(p[1] for p in v), 3)) for _, v in sorted(bins.items())] + [(1.0, 1.0)]

def swift_pairs(name, ch):
    body = ",\n        ".join(", ".join(f"({x}, {y})" for x, y in ch[i:i + 4]) for i in range(0, len(ch), 4))
    return f"    static let {name}: [(x: Double, y: Double)] = [\n        {body},\n    ]\n"
rgb = lambda c: "0x%02x%02x%02x" % c[:3]
out = f"""// GENERATED by factory/tools/switch-artwork/derive_switch_profile.py from Mac captures of SwiftUI's switch at scale 2.5 (light appearance).
// Numbers only: end-cap outlines, flat state colours and a disabled edge-coverage curve measured from reference renders. No Apple artwork is embedded.
// Cap outlines are in points, measured from the top-left corner of the shape (x grows away from the end, y shrinks to 0 at the straight top edge).
enum SwitchArtworkData {{
{swift_pairs("trackCap", pt(track))}
{swift_pairs("knobCap", pt(knob))}
    /// Flat track colours (0xRRGGBB): enabled on/off, disabled on/off.
    static let trackOn: UInt32 = {rgb(flat_on(on))}
    static let trackOff: UInt32 = {rgb(flat_off(off))}
    static let trackOnDisabled: UInt32 = {rgb(flat_on(don))}
    static let trackOffDisabled: UInt32 = {rgb(flat_off(doff))}

    /// Disabled controls cover the track edge less than enabled ones: (enabled coverage, disabled coverage) pairs, ascending.
    static let disabledEdgeCoverage: [(enabled: Double, disabled: Double)] = [
        {", ".join(f"({a}, {b})" for a, b in lut)},
    ]
}}
"""
Path(sys.argv[2] if len(sys.argv) > 2 else "/dev/stdout").write_text(out)

# --- golden probes for the unit tests: every 3rd pixel of each state's 135 x 60 switch, as rows of rrggbb strings (the Mac pixels over white)
if len(sys.argv) > 3:
    def rows(im): return [''.join('%02x%02x%02x' % im[x, y] for x in range(0, 135, 3)) for y in range(0, 60, 3)]
    g = ["// GENERATED by factory/tools/switch-artwork/derive_switch_profile.py: every 3rd pixel (x, y) of SwiftUI's switch at scale 2.5 over white.",
         "enum SwitchArtworkGolden {"]
    for name, im in (("on", on), ("off", off), ("onDisabled", don), ("offDisabled", doff)):
        g.append(f"    static let {name}: [String] = [")
        g += [f'        "{r}",' for r in rows(im)]
        g.append("    ]")
    g.append("}")
    Path(sys.argv[3]).write_text("\n".join(g) + "\n")
