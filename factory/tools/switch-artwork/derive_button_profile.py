#!/usr/bin/env python3
"""Derives packages/SwiftRightHost/Sources/SwiftRightHost/ButtonArtworkData.swift (+ golden test probes) from Mac captures of SwiftUI's Button styles
(button-styles/button_styles_probe.swift: `Button("Run") {}` per style, enabled and disabled, scale 2.5, light appearance, an NSHostingView in a window that is
never shown). Numbers only, never pixels: the corner outline (points), the flat fill colours and the label colours of each look. See derive_checkbox_profile.py.

usage: derive_button_profile.py <captures dir (button-styles/captures)> <out ButtonArtworkData.swift> [golden.swift]
The captures are 800x600 with the 48 x 24 pt button (120 x 60 px) at (340, 270) px, label "Run". The corner outline comes from the prominent capture
(white to accent blue: 255 levels of contrast; the bordered fill is only 20 levels from white, which quantises the outline coarsely)."""
import sys
from collections import Counter
from pathlib import Path
from PIL import Image

S = 2.5; X0, Y0, W, H = 340, 270, 120, 60
root = Path(sys.argv[1])
def load(n): return Image.open(root / f"{n}.png").convert("RGB").load()
im = {n: load(n) for n in ("bordered", "bordered-dis", "borderedProminent", "prominent-dis", "borderless", "borderless-dis", "plain-dis")}
flat = lambda n: im[n][X0 + 10, Y0 + 30]                    # inside the body, left of the label
prom = im["borderedProminent"]; fill_prom = flat("borderedProminent")
K = 24
cov = lambda x, y: max(0.0, min(1.0, (255 - prom[X0 + x, Y0 + y][0]) / (255 - fill_prom[0])))
pts = []
for y in range(0, K):                                   # left boundary of row y (the uncovered run), where it is inside the K window
    x = sum(1 - cov(x, y) for x in range(0, K))
    if x < K - 0.5: pts.append((x, y + 0.5))
for x in range(0, K):                                   # top boundary of column x
    y = sum(1 - cov(x, y) for y in range(0, K))
    if y < K - 0.5: pts.append((x + 0.5, y))
pts.append((float(K), 0.0))
pts.sort(); chain = []
for x, y in pts:
    x, y = round(x / S, 4), round(y / S, 4)
    if chain and x <= chain[-1][0] + 1e-9: continue
    if chain and y > chain[-1][1] + 1e-9: continue
    chain.append((x, y))
if chain[0][0] > 0.0: chain.insert(0, (0.0, chain[0][1]))
# label colour: the colour of the full-coverage glyph pixels, i.e. the most common colour of the label region other than the background under it
def ink(n, bg):
    c = Counter(im[n][x, y] for y in range(Y0 + 10, Y0 + 50) for x in range(X0 + 20, X0 + 100) if im[n][x, y] != bg)
    return c.most_common(1)[0][0]
rgb = lambda c: "0x%02x%02x%02x" % c[:3]
white = (255, 255, 255)
lab = dict(bordered=ink("bordered", flat("bordered")), borderedDis=ink("bordered-dis", flat("bordered-dis")),
           prominent=ink("borderedProminent", fill_prom), prominentDis=ink("prominent-dis", flat("prominent-dis")),
           borderless=ink("borderless", white), borderlessDis=ink("borderless-dis", white), plainDis=ink("plain-dis", white))
body = ",\n        ".join(", ".join(f"({x}, {y})" for x, y in chain[i:i + 4]) for i in range(0, len(chain), 4))
Path(sys.argv[2]).write_text(f"""// GENERATED by factory/tools/switch-artwork/derive_button_profile.py from Mac captures of SwiftUI's Button styles at scale 2.5, light.
// Numbers only: the corner outline, the flat fills and the label colours. No Apple artwork is embedded.
enum ButtonArtworkData {{
    /// Top-left corner of the button in points: (x from the left edge, y of the button's top edge above that column); y reaches 0 at the straight top.
    static let corner: [(x: Double, y: Double)] = [
        {body},
    ]
    // `.bordered` (and `.automatic`)
    static let fill: UInt32 = {rgb(flat("bordered"))}
    static let fillDisabled: UInt32 = {rgb(flat("bordered-dis"))}
    static let label: UInt32 = {rgb(lab["bordered"])}
    static let labelDisabled: UInt32 = {rgb(lab["borderedDis"])}
    // `.borderedProminent` (and the default button, `.keyboardShortcut(.defaultAction)`)
    static let prominentFill: UInt32 = {rgb(fill_prom)}
    static let prominentFillDisabled: UInt32 = {rgb(flat("prominent-dis"))}
    static let prominentLabel: UInt32 = {rgb(lab["prominent"])}
    static let prominentLabelDisabled: UInt32 = {rgb(lab["prominentDis"])}
    // `.borderless`: label only. `.plain`: the label keeps the colour it gives itself; disabled it dims to this.
    static let borderlessLabel: UInt32 = {rgb(lab["borderless"])}
    static let borderlessLabelDisabled: UInt32 = {rgb(lab["borderlessDis"])}
    static let plainLabelDisabled: UInt32 = {rgb(lab["plainDis"])}
}}
""")
print("fills", flat("bordered"), flat("bordered-dis"), fill_prom, flat("prominent-dis"), "labels", lab, "corner points", len(chain))
if len(sys.argv) > 3:
    # probes: every 3rd pixel of the button rectangle, with the label region (x 20..100, y 10..50) blanked to the fill (the label is not artwork)
    def rows(n):
        fill = flat(n); out = []
        for y in range(0, H, 3):
            r = ""
            for x in range(0, W, 3):
                c = fill if (20 <= x < 100 and 10 <= y < 50) else im[n][X0 + x, Y0 + y]
                r += "%02x%02x%02x" % c
            out.append(r)
        return out
    g = ["// GENERATED by factory/tools/switch-artwork/derive_button_profile.py: every 3rd pixel of SwiftUI's 120 x 60 px Button at scale 2.5 over white; the label region is the fill.", "enum ButtonArtworkGolden {"]
    for name, n in (("enabled", "bordered"), ("disabled", "bordered-dis"), ("prominent", "borderedProminent"), ("prominentDisabled", "prominent-dis")):
        g.append(f"    static let {name}: [String] = [")
        g += [f'        "{r}",' for r in rows(n)]
        g.append("    ]")
    g.append("}")
    Path(sys.argv[3]).write_text("\n".join(g) + "\n")
