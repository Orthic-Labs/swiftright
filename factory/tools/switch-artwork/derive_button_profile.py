#!/usr/bin/env python3
"""Derives packages/SwiftRightHost/Sources/SwiftRightHost/ButtonArtworkData.swift (+ golden test probes) from Mac captures of SwiftUI's default
`Button("Run") {}` (the bordered macOS push button) enabled and disabled at scale 2.5, light appearance. Numbers only, never pixels:
the corner outline (points), the flat fill colours and the label colours. See derive_checkbox_profile.py.

usage: derive_button_profile.py <dir with button-enabled-v1 and button-disabled-v1 (each mac/run-01.png)> <out ButtonArtworkData.swift> [golden.swift]
The captures are 800x600 at scale 2.5 with the 48 x 24 pt button (120 x 60 px) at (65, 20) px, label "Run"."""
import sys
from pathlib import Path
from PIL import Image

S = 2.5; X0, Y0, W, H = 65, 20, 120, 60
root = Path(sys.argv[1])
def load(n): return Image.open(root / n / "mac/run-01.png").convert("RGB").load()
en, dis = load("button-enabled-v1"), load("button-disabled-v1")
fill_en, fill_dis = en[X0 + 10, Y0 + 30], dis[X0 + 10, Y0 + 30]     # flat, left of the label
K = 24
cov = lambda x, y: max(0.0, min(1.0, (255 - en[X0 + x, Y0 + y][0]) / (255 - fill_en[0])))
pts = []
for y in range(0, K):                                   # left boundary of row y (the uncovered run), where it is inside the K window
    x = sum(1 - cov(x, y) for x in range(0, K))
    if x < K - 0.5: pts.append((x, y + 0.5))
for x in range(0, K):                                   # top boundary of column x
    y = sum(1 - cov(x, y) for y in range(0, K))
    if y < K - 0.5: pts.append((x + 0.5, y))
pts.append((float(K), 0.0))
pts.sort(); chain = []
for x, y in pts:
    x, y = round(x / S, 4), round(y / S, 4)
    if chain and x <= chain[-1][0] + 1e-9: continue
    if chain and y > chain[-1][1] + 1e-9: continue
    chain.append((x, y))
if chain[0][0] > 0.0: chain.insert(0, (0.0, chain[0][1]))
# label colour: the darkest pixel (a full-coverage glyph pixel) of the label region
def darkest(im): return min((im[x, y] for y in range(Y0 + 10, Y0 + 50) for x in range(X0 + 20, X0 + 100)), key=lambda c: c[0])
lab_en, lab_dis = darkest(en), darkest(dis)
rgb = lambda c: "0x%02x%02x%02x" % c[:3]
body = ",\n        ".join(", ".join(f"({x}, {y})" for x, y in chain[i:i + 4]) for i in range(0, len(chain), 4))
Path(sys.argv[2]).write_text(f"""// GENERATED by factory/tools/switch-artwork/derive_button_profile.py from Mac captures of SwiftUI's default Button (the bordered push button) at scale 2.5, light.
// Numbers only: the corner outline, the flat fills and the label colours. No Apple artwork is embedded.
enum ButtonArtworkData {{
    /// Top-left corner of the button in points: (x from the left edge, y of the button's top edge above that column); y reaches 0 at the straight top.
    static let corner: [(x: Double, y: Double)] = [
        {body},
    ]
    static let fill: UInt32 = {rgb(fill_en)}
    static let fillDisabled: UInt32 = {rgb(fill_dis)}
    static let label: UInt32 = {rgb(lab_en)}
    static let labelDisabled: UInt32 = {rgb(lab_dis)}
}}
""")
print("fill", fill_en, fill_dis, "label", lab_en, lab_dis, "corner points", len(chain))
if len(sys.argv) > 3:
    # probes: every 3rd pixel of the button rectangle, with the label region (x 20..100, y 10..50) blanked to the fill (the label is not artwork)
    def rows(im, fill):
        out = []
        for y in range(0, H, 3):
            r = ""
            for x in range(0, W, 3):
                c = fill if (20 <= x < 100 and 10 <= y < 50) else im[X0 + x, Y0 + y]
                r += "%02x%02x%02x" % c
            out.append(r)
        return out
    g = ["// GENERATED by factory/tools/switch-artwork/derive_button_profile.py: every 3rd pixel of SwiftUI's 120 x 60 px Button at scale 2.5 over white; the label region is the fill.", "enum ButtonArtworkGolden {"]
    for name, im, fill in (("enabled", en, fill_en), ("disabled", dis, fill_dis)):
        g.append(f"    static let {name}: [String] = [")
        g += [f'        "{r}",' for r in rows(im, fill)]
        g.append("    ]")
    g.append("}")
    Path(sys.argv[3]).write_text("\n".join(g) + "\n")
