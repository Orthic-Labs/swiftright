#!/usr/bin/env python3
"""Derives packages/SwiftRightHost/Sources/SwiftRightHost/CheckboxArtworkData.swift (+ golden test probes) from Mac captures of SwiftUI's
default (checkbox) Toggle at scale 2.5: the rounded-square outline, the check-mark stroke (polyline + width) and the four flat state colours.
Numbers only, never pixels; see derive_switch_profile.py.

usage: derive_checkbox_profile.py <dir with checkbox-on-v1, checkbox-off-v1, checkbox-on-disabled-v1, checkbox-off-disabled-v1 (each mac/run-01.png)> <out SwiftData.swift> [golden.swift]
The captures are 800x600 at scale 2.5 with the 16 x 16 pt box at the top-left (40 x 40 px)."""
import sys, math, bisect
from pathlib import Path
from PIL import Image

S = 2.5; N = 40
root = Path(sys.argv[1])
def load(n): return Image.open(root / n / "mac/run-01.png").convert("RGB").load()
on, off, don, doff = (load(n) for n in ("checkbox-on-v1", "checkbox-off-v1", "checkbox-on-disabled-v1", "checkbox-off-disabled-v1"))

# --- corner outline (top-left), from the ON capture's R channel (box R=0 on white 255). K px of the edge only, so the check mark is never summed.
K = 9
box_cov = lambda x, y: (255 - on[x, y][0]) / 255
pts = []
for y in range(0, 20):                                   # steep part: left boundary of row y (the uncovered run), only where it is inside the K window
    x = sum(1 - box_cov(x, y) for x in range(0, K))
    if x < K - 0.5: pts.append((x, y + 0.5))
for x in range(0, 24):                                   # flat part: top boundary of column x (the uncovered run), only where it is inside the K window
    y = sum(1 - box_cov(x, y) for y in range(0, K))
    if y < K - 0.5: pts.append((x + 0.5, y))
pts.append((24.0, 0.0))
pts.sort(); chain = []
for x, y in pts:
    x, y = round(x / S, 4), round(y / S, 4)
    if chain and x <= chain[-1][0] + 1e-9: continue
    if chain and y > chain[-1][1] + 1e-9: continue
    chain.append((x, y))
# the corner starts at the left edge (x = 0) at some height: anchor it there
if chain[0][0] > 0.0: chain.insert(0, (0.0, chain[0][1]))

# --- check mark: two tapered round-capped strokes (left arm, right arm), white on the ON box. Fitted to the 2.5 render by coordinate descent with the same
# hard-sample coverage the host rasteriser uses (5 x 5 samples per pixel), so the fit and the renderer agree.
samples = [(x, y, on[x, y][0] / 255) for y in range(8, 34) for x in range(8, 34)]
def seg(px, py, ax, ay, bx, by, ra, rb):      # signed distance to a tapered round-capped stroke from (a, radius ra) to (b, radius rb)
    dx, dy = bx - ax, by - ay; l = dx * dx + dy * dy
    t = max(0, min(1, ((px - ax) * dx + (py - ay) * dy) / l)) if l else 0
    return math.hypot(px - (ax + t * dx), py - (ay + t * dy)) - (ra + (rb - ra) * t)
def coverage(px, py, q, ss=5):
    c = 0
    for sy in range(ss):
        for sx in range(ss):
            x = (px + (sx + .5) / ss) / S; y = (py + (sy + .5) / ss) / S
            if seg(x, y, q[0], q[1], q[2], q[3], q[8], q[9]) <= 0 or seg(x, y, q[4], q[5], q[6], q[7], q[10], q[11]) <= 0: c += 1
    return c / (ss * ss)
def err(q): return sum((coverage(x, y, q) - v) ** 2 for x, y, v in samples)
best = [4.251, 8.54, 6.976, 11.762, 7.234, 11.771, 11.945, 4.526, 1.04, 1.04, 0.966, 1.047]; be = err(best); step = [0.2] * 8 + [0.1] * 4
while max(step) > 0.01:
    improved = False
    for i in range(12):
        for sgn in (1, -1):
            c = best[:]; c[i] += sgn * step[i]; e = err(c)
            if e < be: best, be, improved = c, e, True
    if not improved: step = [s / 2 for s in step]
check = [round(v, 3) for v in best]       # left arm x1 y1 x2 y2, right arm x1 y1 x2 y2, then the four radii (left start/end, right start/end)

flat = lambda im, p: im[p]
colours = dict(on=flat(on, (4, 20)), off=flat(off, (20, 20)), onDisabled=flat(don, (4, 20)), offDisabled=flat(doff, (20, 20)))
# the check colour in the disabled ON state (flat inside the thick part of the stroke)
checkDisabled = don[int((check[4] + 0.2) * S), int((check[5] - 0.2) * S)]
rgb = lambda c: "0x%02x%02x%02x" % c[:3]
body = ",\n        ".join(", ".join(f"({x}, {y})" for x, y in chain[i:i + 4]) for i in range(0, len(chain), 4))
Path(sys.argv[2]).write_text(f"""// GENERATED by factory/tools/switch-artwork/derive_checkbox_profile.py from Mac captures of SwiftUI's default Toggle (a checkbox) at scale 2.5, light.
// Numbers only: the corner outline of the 16 x 16 pt box, the check-mark stroke and the flat state colours. No Apple artwork is embedded.
enum CheckboxArtworkData {{
    /// Top-left corner of the box in points: (x from the left edge, y of the box's top edge above that column); y reaches 0 at the straight top.
    static let corner: [(x: Double, y: Double)] = [
        {body},
    ]
    /// Check mark: two tapered round-capped strokes, each (x1, y1, x2, y2, radius at 1, radius at 2) in points from the box's top-left: the left arm,
    /// then the right arm.
    static let checkStrokes: [[Double]] = [
        {check[:4] + check[8:10]},
        {check[4:8] + check[10:12]},
    ]
    static let boxOn: UInt32 = {rgb(colours['on'])}
    static let boxOff: UInt32 = {rgb(colours['off'])}
    static let boxOnDisabled: UInt32 = {rgb(colours['onDisabled'])}
    static let boxOffDisabled: UInt32 = {rgb(colours['offDisabled'])}
    static let checkOn: UInt32 = 0xffffff
    static let checkOnDisabled: UInt32 = {rgb(checkDisabled)}
}}
""")
print("check", check, "fit error", round(be, 3), "colours", colours, "checkDisabled", checkDisabled)
if len(sys.argv) > 3:
    def rows(im): return [''.join('%02x%02x%02x' % im[x, y] for x in range(0, N, 2)) for y in range(0, N, 2)]
    g = ["// GENERATED by factory/tools/switch-artwork/derive_checkbox_profile.py: every 2nd pixel (x, y) of SwiftUI's checkbox at scale 2.5 over white.", "enum CheckboxArtworkGolden {"]
    for name, im in (("on", on), ("off", off), ("onDisabled", don), ("offDisabled", doff)):
        g.append(f"    static let {name}: [String] = [")
        g += [f'        "{r}",' for r in rows(im)]
        g.append("    ]")
    g.append("}")
    Path(sys.argv[3]).write_text("\n".join(g) + "\n")
