#!/usr/bin/env node
// The repair guard script is OWNED by RightKit (rightkit/packages/release/msix-repair-guard.ps1, exported by msix-repair-guard.mjs).
// guard/msix-repair-guard.ps1 is a byte copy pinned by guard/rightkit-pin.json; Sources/SwiftRightBridge/RepairGuardScript.swift embeds it.
//   node tools/gen-repair-guard.mjs                          regenerate the Swift file from guard/msix-repair-guard.ps1
//   node tools/gen-repair-guard.mjs --check                  exit 1 when the Swift file or the pin is stale
//   node tools/gen-repair-guard.mjs --sync <rightkit-root> --commit <sha> --rightkit-version <v>
//                                                            copy the canonical file, write the pin, regenerate
import { createHash } from "node:crypto";
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const guardPath = path.join(root, "guard", "msix-repair-guard.ps1");
const pinPath = path.join(root, "guard", "rightkit-pin.json");
const argv = process.argv.slice(2);
const arg = (name) => { const i = argv.indexOf(name); return i >= 0 ? argv[i + 1] : undefined; };
const sha = (text) => createHash("sha256").update(Buffer.from(text, "utf8")).digest("hex");
const norm = (text) => text.replace(/\r\n/g, "\n");

if (arg("--sync")) {
  const rk = path.resolve(arg("--sync"));
  const canonical = path.join(rk, "packages", "release", "msix-repair-guard.ps1");
  copyFileSync(canonical, guardPath);
  const text = norm(readFileSync(guardPath, "utf8"));
  const guardVersion = Number(/^\$GuardVersion = (\d+)$/m.exec(text)?.[1]);
  if (!arg("--commit") || !arg("--rightkit-version")) throw new Error("--sync needs --commit and --rightkit-version");
  writeFileSync(pinPath, JSON.stringify({
    canonical: "rightkit/packages/release/msix-repair-guard.ps1",
    rightkitRepository: "https://github.com/Orthic-Labs/rightkit",
    rightkitCommit: arg("--commit"),
    rightkitPackageVersion: arg("--rightkit-version"),
    guardVersion,
    sha256: sha(text),
  }, null, 2) + "\n");
}

const src = norm(readFileSync(guardPath, "utf8"));
if (src.includes('"""#')) throw new Error("script contains the raw-string terminator");
const out = `// GENERATED by tools/gen-repair-guard.mjs from guard/msix-repair-guard.ps1 (a byte copy of the RightKit canonical file pinned in guard/rightkit-pin.json). Do not edit.
enum RepairGuardScript {
    /// SHA-256 (hex) of \`source\` as one LF-terminated file.
    static let sha256 = "${sha(src)}"
    static let source = #"""
${src.replace(/\n$/, "")}
"""#
}
`;
const target = path.join(root, "Sources", "SwiftRightBridge", "RepairGuardScript.swift");
if (argv.includes("--check")) {
  let cur = ""; try { cur = readFileSync(target, "utf8"); } catch {}
  const pin = JSON.parse(readFileSync(pinPath, "utf8"));
  if (cur !== out) { console.error("RepairGuardScript.swift is stale; run node tools/gen-repair-guard.mjs"); process.exit(1); }
  if (pin.sha256 !== sha(src)) { console.error("guard/rightkit-pin.json does not match guard/msix-repair-guard.ps1; run --sync from the RightKit checkout"); process.exit(1); }
} else { writeFileSync(target, out); console.log("wrote " + target); }
