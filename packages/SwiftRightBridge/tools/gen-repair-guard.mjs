#!/usr/bin/env node
// The repair guard script is OWNED by RightKit: rightkit/packages/release/msix-repair-guard.ps1, returned by
// msixRepairGuard() in the installed @rightkit/release package (msix-repair-guard.mjs). This generator reads that
// text and writes the two derived files; nothing is hand-copied from a RightKit checkout.
//   guard/msix-repair-guard.ps1 is generated (tests read it); guard/rightkit-pin.json pins its sha256;
//   Sources/SwiftRightBridge/RepairGuardScript.swift embeds it.
//   node tools/gen-repair-guard.mjs                          regenerate both files from the installed @rightkit/release
//   node tools/gen-repair-guard.mjs --check                  exit 1 when a generated file or the pin is stale
//   node tools/gen-repair-guard.mjs --sync --commit <sha>    also rewrite guard/rightkit-pin.json for the installed package
//                                                            (--commit is the RightKit commit that package was built from)
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repo = path.resolve(root, "..", "..");
const release = path.join(repo, "node_modules", "@rightkit", "release");
const guardPath = path.join(root, "guard", "msix-repair-guard.ps1");
const pinPath = path.join(root, "guard", "rightkit-pin.json");
const target = path.join(root, "Sources", "SwiftRightBridge", "RepairGuardScript.swift");
const argv = process.argv.slice(2);
const arg = (name) => { const i = argv.indexOf(name); return i >= 0 ? argv[i + 1] : undefined; };
const fail = (message) => { console.error(message); process.exit(1); };

let guardApi;
try {
  guardApi = await import(pathToFileURL(path.join(release, "msix-repair-guard.mjs")).href);
} catch (error) {
  throw new Error(`@rightkit/release is not installed at ${release} (pnpm install at the repository root): ${error.message}`);
}
const guard = guardApi.msixRepairGuard();
const src = guard.text;
if (src.includes('"""#')) throw new Error("script contains the raw-string terminator");
const packageVersion = JSON.parse(readFileSync(path.join(release, "package.json"), "utf8")).version;

if (argv.includes("--sync")) {
  const commit = arg("--commit");
  if (!commit) throw new Error(`--sync needs --commit (the RightKit commit @rightkit/release ${packageVersion} was built from)`);
  writeFileSync(pinPath, JSON.stringify({
    canonical: "rightkit/packages/release/msix-repair-guard.ps1",
    rightkitRepository: "https://github.com/Orthic-Labs/rightkit",
    rightkitCommit: commit,
    rightkitPackageVersion: packageVersion,
    guardVersion: guard.guardVersion,
    sha256: guard.sha256,
  }, null, 2) + "\n");
}

const out = `// GENERATED by tools/gen-repair-guard.mjs from msixRepairGuard() in @rightkit/release (msix-repair-guard.ps1, pinned in guard/rightkit-pin.json). Do not edit.
enum RepairGuardScript {
    /// SHA-256 (hex) of \`source\` as one LF-terminated file.
    static let sha256 = "${guard.sha256}"
    static let source = #"""
${src.replace(/\n$/, "")}
"""#
}
`;

if (argv.includes("--check")) {
  let cur = ""; try { cur = readFileSync(target, "utf8"); } catch {}
  let copy = ""; try { copy = readFileSync(guardPath, "utf8"); } catch {}
  let pin = {}; try { pin = JSON.parse(readFileSync(pinPath, "utf8")); } catch {}
  if (cur !== out) fail("RepairGuardScript.swift is stale; run node tools/gen-repair-guard.mjs");
  if (copy !== src) fail("guard/msix-repair-guard.ps1 is stale; run node tools/gen-repair-guard.mjs");
  if (pin.sha256 !== guard.sha256) fail("guard/rightkit-pin.json does not match @rightkit/release msixRepairGuard(); run node tools/gen-repair-guard.mjs --sync --commit <rightkit-sha>");
} else {
  writeFileSync(guardPath, src);
  writeFileSync(target, out);
  console.log("wrote " + guardPath + " and " + target);
}
