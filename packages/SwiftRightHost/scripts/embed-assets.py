#!/usr/bin/env python3
"""Embeds Assets/SystemImageAssets.json into Sources/SwiftRightHost/SystemImageTableData.swift (a raw string literal).
Run after editing the JSON; the test SystemImageTableTests.testEmbeddedTableEqualsAssetFile fails when they drift."""
import json
from pathlib import Path
root = Path(__file__).resolve().parent.parent
src = (root / "Assets/SystemImageAssets.json").read_text(encoding="utf-8")
json.loads(src)
assert '"""#' not in src
out = root / "Sources/SwiftRightHost/SystemImageTableData.swift"
out.write_text("// Generated by scripts/embed-assets.py from Assets/SystemImageAssets.json; do not edit.\nenum SystemImageTableData {\n    static let json = #\"\"\"\n" + src.rstrip("\n") + "\n\"\"\"#\n}\n", encoding="utf-8")
print("wrote", out)
